const habits = { runner: 'play', scout: 'explore', cuddler: 'affection' };

function familyForms(lineage, starter, rows) {
  return Object.fromEntries(Object.entries(rows).map(([suffix, row]) => {
    const [name, description, ballReaction, exploreReaction, petReaction] = row;
    const [first, second] = suffix.split('-');
    const stage = suffix === starter ? 1 : second ? 3 : 2;
    const parent = stage === 1 ? 'egg' : lineage + '-' + (second ? first : starter);
    return [
      lineage + '-' + suffix,
      { name, description, lineage, stage, parent, habit: habits[second ?? first], ballReaction, exploreReaction, petReaction }
    ];
  }));
}

